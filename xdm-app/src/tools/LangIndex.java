import java.io.IOException;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Properties;
import java.util.TreeMap;
import java.util.stream.Stream;

/**
 * Build step (xdm-app pom, process-resources): writes {@code lang/index}, one {@code code=LANGUAGE_NAME}
 * line per {@code lang/<code>.txt}, so the Settings language list reads one small file instead of every
 * translation (docs/i18n.md). Sorted by code and without a date, so the output only changes with the files.
 *
 * <p>Run with the source launcher: {@code java LangIndex.java <lang dir> <index file>}.
 */
public class LangIndex {
    public static void main(String[] args) throws IOException {
        Path dir = Path.of(args[0]);
        Path out = Path.of(args[1]);
        TreeMap<String, String> names = new TreeMap<>();
        try (Stream<Path> files = Files.list(dir)) {
            for (Path f : (Iterable<Path>) files::iterator) {
                String file = f.getFileName().toString();
                if (!file.endsWith(".txt")) continue;
                String code = file.substring(0, file.length() - ".txt".length());
                Properties p = new Properties();
                try (Reader r = Files.newBufferedReader(f, StandardCharsets.UTF_8)) {
                    p.load(r);
                }
                String name = p.getProperty("LANGUAGE_NAME", "").strip();
                names.put(code, name.isEmpty() ? code : name);
            }
        }
        StringBuilder sb = new StringBuilder("# Generated by src/tools/LangIndex.java from lang/*.txt; do not edit\n");
        names.forEach((code, name) -> sb.append(code).append('=').append(escape(name)).append('\n'));
        Files.createDirectories(out.getParent());
        Files.writeString(out, sb, StandardCharsets.UTF_8);
        System.out.println("LangIndex: " + names.size() + " languages -> " + out);
    }

    // Enough of Properties' escaping for a stripped one-line name: backslashes and line breaks.
    private static String escape(String s) {
        return s.replace("\\", "\\\\").replace("\n", "\\n").replace("\r", "\\r");
    }
}
