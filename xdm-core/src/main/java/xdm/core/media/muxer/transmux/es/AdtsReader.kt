package xdm.core.media.muxer.transmux.es

import xdm.core.media.muxer.transmux.io.ParsableBitArray
import xdm.core.media.muxer.transmux.mp4.SampleEntries
import xdm.core.media.muxer.transmux.sample.Codec
import xdm.core.media.muxer.transmux.sample.Track
import xdm.core.util.Logger

/**
 * AAC reader for ADTS-framed streams (TS stream_type 0x0F). Each ADTS frame becomes one MP4
 * sample of 1024 audio samples. The ADTS header is stripped (MP4 stores raw AAC) and an
 * AudioSpecificConfig is synthesized for the esds box. Timestamps are generated by counting
 * frames from the first PES PTS, which yields gapless audio; a large PTS jump re-anchors.
 *
 * A frame split across PES packets is carried over and completed by the next [consume]; the PES
 * PTS belongs to the first frame that starts inside that PES. The 0xFFF sync also occurs inside
 * raw AAC data, so a header found by scanning is only accepted when another header with the same
 * sampling frequency follows it.
 */
class AdtsReader(private val sink: SampleSink) : ElementaryStreamReader {
    override val track = Track(Codec.AAC)

    private val clock = FrameClock()
    /** profile/frequency/channels of the frames being read; -1 before the first frame. */
    private var configKey = -1
    /** Sampling rate of the current config (the track timescale stays the first config's). */
    private var rate = 0
    private var descriptionIndex = 1
    private val pending = ByteArrayBuilder(MAX_FRAME)
    /** Whether [pending] starts at a frame boundary we were already in sync with. */
    private var pendingInSync = false
    /** PTS of the PES the carried partial frame started in, when that frame was its first. */
    private var carriedPts = -1L

    override fun consume(data: ByteArray, offset: Int, length: Int, pts: Long, dts: Long) {
        val buf: ByteArray
        var i: Int
        val end: Int
        val carried = pending.size
        if (carried > 0) {
            buf = ByteArray(carried + length)
            System.arraycopy(pending.buffer, 0, buf, 0, carried)
            System.arraycopy(data, offset, buf, carried, length)
            i = 0
            end = buf.size
            pending.reset()
        } else {
            buf = data
            i = offset
            end = offset + length
        }
        // Frames starting at or after this index start in the current PES.
        val pesStart = i + carried
        var pesAnchor = pts
        var carryAnchor = carriedPts
        carriedPts = -1
        var inSync = carried > 0 && pendingInSync

        while (i + 7 <= end) {
            if (!isSync(buf, i)) {
                i++; inSync = false
                continue
            }
            val frameLength = frameLength(buf, i)
            if (frameLength < 7) { i++; inSync = false; continue }
            if (i + frameLength > end) break // incomplete: carried over below
            if (!inSync && !confirmedByNextHeader(buf, i, i + frameLength, end)) {
                i++; continue
            }
            val protectionAbsent = buf[i + 1].toInt() and 0x01
            val profile = (buf[i + 2].toInt() and 0xC0) shr 6           // audioObjectType - 1
            val freqIndex = (buf[i + 2].toInt() and 0x3C) shr 2
            val channelConfig = ((buf[i + 2].toInt() and 0x01) shl 2) or ((buf[i + 3].toInt() and 0xC0) shr 6)
            val key = (profile shl 8) or (freqIndex shl 4) or channelConfig
            val headerLen = if (protectionAbsent == 1) 7 else 9
            var pceBytes = 0
            if (key != configKey) {
                pceBytes = switchConfig(key, profile, freqIndex, channelConfig, buf, i + headerLen, i + frameLength)
                if (pceBytes < 0) { i++; inSync = false; continue }
            }
            val timescale = track.timescale
            val frameTicks = SAMPLES_PER_FRAME * timescale / rate

            val anchor = if (i < pesStart) carryAnchor else pesAnchor
            if (anchor >= 0) {
                clock.anchor(anchor, timescale, frameTicks)
                if (i < pesStart) carryAnchor = -1 else pesAnchor = -1 // only the first frame starting in that PES
            }

            // A PCE moved into the AudioSpecificConfig is taken off the frame, as ffmpeg does.
            val rawStart = i + headerLen + pceBytes
            val rawLen = frameLength - headerLen - pceBytes
            // number_of_raw_data_blocks_in_frame: a frame may carry up to 4 blocks of 1024 samples.
            val samples = SAMPLES_PER_FRAME.toInt() * ((buf[i + 6].toInt() and 3) + 1)
            if (rawLen > 0) {
                val fileOffset = sink.writeSampleData(buf, rawStart, rawLen)
                val ts = clock.current()
                track.samples.add(fileOffset, rawLen, ts, ts, true, descriptionIndex)
                clock.advance(samples, rate, timescale)
            }
            i += frameLength
            inSync = true
        }
        val tail = end - i
        if (tail in 1..MAX_FRAME) {
            pending.write(buf, i, tail)
            carriedPts = if (i < pesStart) carryAnchor else pesAnchor
        }
        pendingInSync = inSync
    }

    override fun finish() {}

    private fun isSync(b: ByteArray, i: Int) =
        (b[i].toInt() and 0xFF) == 0xFF && (b[i + 1].toInt() and 0xF6) == 0xF0 // sync + layer 00

    private fun frameLength(b: ByteArray, i: Int) =
        ((b[i + 3].toInt() and 0x03) shl 11) or ((b[i + 4].toInt() and 0xFF) shl 3) or ((b[i + 5].toInt() and 0xE0) shr 5)

    /** True if a header with the same sampling frequency starts at [next], or [next] is too near [end] to tell. */
    private fun confirmedByNextHeader(b: ByteArray, at: Int, next: Int, end: Int): Boolean {
        if (next + 3 > end) return true
        return isSync(b, next) && (b[next + 2].toInt() and 0x3C) == (b[at + 2].toInt() and 0x3C)
    }

    /**
     * Starts reading frames of a new config. The first one configures the track; a later one (an ad
     * at another sampling rate or channel layout) freezes the first config's sample entry and points
     * the following samples at an entry of their own. With channel_config 0 the layout is in a
     * program_config_element at the start of the frame's raw data ([rawStart] to [rawEnd]): it is
     * moved into the AudioSpecificConfig, as ffmpeg's aac_adtstoasc does. Returns the PCE bytes to
     * take off this frame (0 without one), or -1 for an unusable header.
     */
    private fun switchConfig(key: Int, profile: Int, freqIndex: Int, channelConfig: Int,
                             buf: ByteArray, rawStart: Int, rawEnd: Int): Int {
        if (SAMPLE_RATES[freqIndex] == 0) return -1
        val pce = if (channelConfig == 0) readPce(buf, rawStart, rawEnd) else null
        val target = if (configKey == -1) track else Track(Codec.AAC)
        configure(target, profile, freqIndex, channelConfig, pce)
        if (configKey == -1) {
            track.timescale = track.sampleRate
        } else {
            if (track.sampleEntryBox == null) track.sampleEntryBox = SampleEntries.build(track)
            descriptionIndex = track.descriptionIndexFor(SampleEntries.build(target)!!)
            Logger.info("XDM", "AAC config changed to ${target.sampleRate} Hz, ${target.channelCount} ch (sample entry $descriptionIndex)")
        }
        configKey = key
        rate = SAMPLE_RATES[freqIndex]
        return pce?.consumedBytes ?: 0
    }

    private class Pce(val bits: ByteArray, val bitCount: Int, val channels: Int, val consumedBytes: Int)

    /**
     * Reads a program_config_element (14496-3 4.4.1.1) that opens a raw data block and re-packs it
     * for an AudioSpecificConfig: its byte alignment is relative to where it starts, so it is copied
     * field by field rather than as bytes (like ffmpeg's ff_copy_pce_data). Null if the block does
     * not start with one.
     */
    private fun readPce(buf: ByteArray, start: Int, end: Int): Pce? {
        if (end - start < 4) return null
        val r = ParsableBitArray(buf.copyOfRange(start, end))
        if (r.readBits(3) != 5) return null                      // id_syn_ele: ID_PCE
        val w = BitPacker()
        fun copy(n: Int) = r.readBits(n).also { w.put(it, n) }
        copy(4); copy(2); copy(4)                                // element_instance_tag, object_type, sampling_frequency_index
        val front = copy(4); val side = copy(4); val back = copy(4)
        val lfe = copy(2); val assoc = copy(3); val cc = copy(4)
        if (copy(1) == 1) copy(4)                                // mono_mixdown
        if (copy(1) == 1) copy(4)                                // stereo_mixdown
        if (copy(1) == 1) copy(3)                                // matrix_mixdown
        var channels = 0
        repeat(front + side + back) { channels += if (copy(1) == 1) 2 else 1; copy(4) } // is_cpe, tag_select
        repeat(lfe) { copy(4) }
        channels += lfe
        repeat(assoc) { copy(4) }
        repeat(cc) { copy(5) }
        r.setPosition((r.position() + 7) and 7.inv())            // byte_alignment, in the source...
        val asc = 16                                             // ...and after the 16-bit ASC head in the output
        w.align(asc)
        val comment = copy(8)
        repeat(comment) { copy(8) }
        return Pce(w.toByteArray(), w.bitCount, channels, r.position() / 8)
    }

    /** Minimal MSB-first bit packer for the re-packed PCE. */
    private class BitPacker {
        private val out = java.io.ByteArrayOutputStream()
        private var cur = 0
        private var n = 0
        val bitCount get() = out.size() * 8 + n
        fun put(v: Int, bits: Int) {
            for (k in bits - 1 downTo 0) {
                cur = (cur shl 1) or ((v shr k) and 1)
                if (++n == 8) { out.write(cur); cur = 0; n = 0 }
            }
        }
        /** Pads with zeros so that [offsetBits] + bitCount is a multiple of 8. */
        fun align(offsetBits: Int) { while ((offsetBits + bitCount) % 8 != 0) put(0, 1) }
        fun toByteArray(): ByteArray {
            val r = java.io.ByteArrayOutputStream()
            r.write(out.toByteArray())
            if (n > 0) r.write(cur shl (8 - n))
            return r.toByteArray()
        }
    }

    private fun configure(track: Track, profile: Int, freqIndex: Int, channelConfig: Int, pce: Pce? = null) {
        val audioObjectType = profile + 1
        track.sampleRate = SAMPLE_RATES[freqIndex]
        track.channelCount = pce?.channels ?: if (channelConfig in 1..7) CHANNELS[channelConfig] else channelConfig
        // AudioSpecificConfig: AOT(5) | freqIndex(4) | channelConfig(4) | GASpecificConfig(3) = 16 bits,
        // then the program_config_element when channelConfig is 0 (it starts byte aligned).
        val asc = ByteArray(2) + (pce?.bits ?: ByteArray(0))
        asc[0] = ((audioObjectType shl 3) or (freqIndex shr 1)).toByte()
        asc[1] = (((freqIndex and 0x1) shl 7) or (channelConfig shl 3)).toByte()
        track.audioSpecificConfig = asc
    }

    companion object {
        const val SAMPLES_PER_FRAME = 1024L
        val SAMPLE_RATES = intArrayOf(
            96000, 88200, 64000, 48000, 44100, 32000, 24000, 22050,
            16000, 12000, 11025, 8000, 7350, 0, 0, 0
        )
        val CHANNELS = intArrayOf(0, 1, 2, 3, 4, 5, 6, 8)
        /** The 13-bit ADTS frame_length field's maximum. */
        private const val MAX_FRAME = 8191
    }
}
